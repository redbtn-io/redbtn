// Graph / node / automation EDIT grants for profiled graphs (engine 0.0.295-alpha, redbtn#577).
//
// 0.0.295 maps graph_patch / update_graph / publish_graph (graph:write), delete_graph (graph:delete),
// node_patch / update_node (node:write), delete_node (node:delete) and update_automation /
// enable_automation / disable_automation (automation:write) into DATA_TOOL_RULES. A graph that carries
// ANY capability profile is enforced for every mapped resource, so a profiled graph whose neurons list
// (or whose tool steps call) one of these tools loses it unless its profile grants it.
//
// For profiles whose documented intent is "preserve prior / full access" (PRESERVE_PROFILES, same list as
// 2026-09-30-graph-capability-missing-grants.js) the missing grant is ADDED at selector '*' (appended to an
// existing '*' grant of that resource when there is one). Every other profile is a real jail: its gap is
// REPORTED, never widened (on 2026-10-12 that was Become Ops a4JcJpRij9DV, regenerated by redOps).
//
// Scans the RUNTIME config (published.nodes when published, else nodes; nodeId refs resolved from the
// nodes collection). Before each write the previous `capabilities` is saved to graph_capability_backups;
// the update is conditional on `capabilities` being unchanged. Re-running after apply reports no gaps for
// PRESERVE profiles.
//
// RUN (dry run by default):
//   MONGODB_URI=... node ops/migrations/2026-10-12-graph-edit-grants.mjs --db redbtn [--db redbtn-beta]
//   ... --apply      write
// AFTER: redis PUBLISH graph:invalidate <graphId> for each changed graph (printed at the end), or wait
// the 5-minute GraphRegistry TTL.
// Applied 2026-10-12 to redbtn + redbtn-beta: gemini-37-agent got graph:write and node:write ('*').
import { MongoClient } from 'mongodb';

const argv = process.argv.slice(2);
const APPLY = argv.includes('--apply');
const DBS = argv.flatMap((a, i) => (a === '--db' ? [argv[i + 1]] : [])).filter(Boolean);
const REASON = 'graph-edit-grants 2026-10-12 (engine 0.0.295, redbtn#577)';
const PRESERVE_PROFILES = ['exec-migration', 'gemini-37-agent-capabilities'];
const NEW_RULES = {
  graph_patch: ['graph', 'write'], update_graph: ['graph', 'write'], publish_graph: ['graph', 'write'],
  delete_graph: ['graph', 'delete'],
  node_patch: ['node', 'write'], update_node: ['node', 'write'], delete_node: ['node', 'delete'],
  update_automation: ['automation', 'write'], enable_automation: ['automation', 'write'],
  disable_automation: ['automation', 'write'],
};

function toolNames(steps, out) {
  for (const s of steps || []) {
    if (!s || typeof s !== 'object') continue;
    const c = s.config || {};
    if (s.type === 'neuron') {
      for (const t of Array.isArray(c.tools) ? c.tools : []) {
        const n = typeof t === 'string' ? t : t && (!t.source || t.source === 'native') ? t.name : null;
        if (n && NEW_RULES[n]) out.add(n);
      }
    }
    if (s.type === 'tool' && NEW_RULES[c.toolName]) out.add(c.toolName);
    if (Array.isArray(c.steps)) toolNames(c.steps, out);
  }
  return out;
}

const uri = process.env.MONGODB_URI;
if (!uri || DBS.length === 0) {
  console.error('usage: MONGODB_URI=... node 2026-10-12-graph-edit-grants.mjs --db <name> [--db <name>] [--apply]');
  process.exit(2);
}
const client = new MongoClient(uri);
await client.connect();
const invalidate = [];
try {
  for (const dbn of DBS) {
    const db = client.db(dbn);
    const graphs = await db.collection('graphs').find({ 'capabilities.capabilities': { $type: 'array' } }).toArray();
    for (const g of graphs) {
      const runtimeNodes = g.published && typeof g.published === 'object' ? g.published.nodes || [] : g.nodes || [];
      const used = new Set();
      for (const n of runtimeNodes) {
        const cfg = (n && n.config) || {};
        if (Array.isArray(cfg.steps) && cfg.steps.length) toolNames(cfg.steps, used);
        else if (cfg.nodeId) {
          const nd = await db.collection('nodes').findOne({ nodeId: cfg.nodeId }, { projection: { steps: 1 } });
          if (nd) toolNames(nd.steps, used);
        }
      }
      if (!used.size) continue;
      const caps = g.capabilities.capabilities;
      const covered = (res, act) => caps.some(
        (c) => c.resource === res && Array.isArray(c.actions) && c.actions.includes(act) && (c.selector || '').trim() === '*',
      );
      const gaps = [...new Set([...used].map((t) => NEW_RULES[t].join(':')))].filter((k) => !covered(...k.split(':')));
      const preserve = PRESERVE_PROFILES.includes(g.capabilities.name);
      console.log(`${dbn} ${g.graphId} profile=${g.capabilities.name} uses=[${[...used]}] gaps=[${gaps}] ${preserve ? 'PRESERVE -> grant' : 'JAIL -> report only'}`);
      if (!gaps.length || !preserve) continue;
      const next = JSON.parse(JSON.stringify(g.capabilities));
      for (const k of gaps) {
        const [r, a] = k.split(':');
        const star = next.capabilities.find((c) => c.resource === r && (c.selector || '').trim() === '*');
        if (star) { if (!star.actions.includes(a)) star.actions.push(a); } else next.capabilities.push({ resource: r, actions: [a], selector: '*' });
      }
      if (!APPLY) continue;
      await db.collection('graph_capability_backups').insertOne({ graphId: g.graphId, db: dbn, reason: REASON, previous: g.capabilities, next, at: new Date() });
      const res = await db.collection('graphs').updateOne({ _id: g._id, capabilities: g.capabilities }, { $set: { capabilities: next } });
      console.log(`   applied: ${res.modifiedCount}`);
      if (res.modifiedCount) invalidate.push(g.graphId);
    }
  }
} finally {
  await client.close();
}
console.log(`APPLY=${APPLY} invalidate: ${JSON.stringify(invalidate)}`);
